export interface DesignResult {
  themeName: string
  occasion: Occasion
  style: StyleOption
  band: GuestBand
  budgetMin: number
  budgetMax: number
  decor: string[]
  tip: string
  prepDays: number
}

export function generateDesign(occId: string, styleId: string, bandId: string): DesignResult {
  const occasion = OCCASIONS.find((o) => o.id === occId) ?? OCCASIONS[0]
  const style = STYLES.find((s) => s.id === styleId) ?? STYLES[0]
  const band = GUESTS_BANDS.find((b) => b.id === bandId) ?? GUESTS_BANDS[1]
  const estimate = occasion.base + style.perGuest * band.guests
  return {
    themeName: THEME_NAMES[occasion.id][style.id],
    occasion,
    style,
    band,
    budgetMin: Math.round((estimate * 0.85) / 100_000) * 100_000,
    budgetMax: Math.round((estimate * 1.15) / 100_000) * 100_000,
    decor: DECOR_PARTS[occasion.id],
    tip: AI_TIPS[occasion.id],
    prepDays: estimate > 40_000_000 ? 21 : estimate > 20_000_000 ? 14 : 10,
  }
}

